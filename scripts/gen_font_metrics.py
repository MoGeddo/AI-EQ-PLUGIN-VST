#!/usr/bin/env python3
"""Regenerate Source/ui/FontMetrics.h from the shipped Cairo face.

The footer's sentence is measured by an arithmetic gate (Tests/test_layout.cpp) that has no
JUCE and therefore no font.  Rather than teach that gate to guess, the advances are extracted
here, once, from the same `assets/Cairo-Regular.ttf` the plugin embeds - so the gate measures
the font the product draws with.

    python3 -m venv .venv && .venv/bin/pip install fonttools
    .venv/bin/python scripts/gen_font_metrics.py
"""
import pathlib
import sys

from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
TTF = ROOT / "plugin/Source/assets/Cairo-Regular.ttf"
OUT = ROOT / "plugin/Source/ui/FontMetrics.h"

HEADER = r'''// ui/FontMetrics.h - Cairo's own advance widths, as numbers a test can use.
//
// Generated by scripts/gen_font_metrics.py from plugin/Source/assets/Cairo-Regular.ttf
// (the face the plugin embeds).  Do not edit by hand: regenerate.
//
// Why: the footer's sentence is the one thing on this panel that has shipped broken three
// times, and every one of those passed a gate that never measured it - because measuring text
// needs a font and the arithmetic gates have no JUCE.  `advance()` reproduces JUCE's
// getStringWidth for a run of Latin text to within a fraction of a pixel, which is all a
// layout decision needs.  Non-ASCII text is measured with the table's mean advance and must
// be checked the slow way.
#pragma once

#include <cstddef>

namespace aeq::ui::metrics
{

// unitsPerEm = {upm}: each value below is advance / {upm}.
//
// The key is the **code point**, not a byte.  It used to be `char` and the table only held
// 32..126, so every non-ASCII character the panel draws was silently measured as two unknown
// bytes: the separator in "1.25 kHz  \u00b7  Q 1.40" is two bytes of UTF-8, each charged the
// 0.55 em fallback, so a 114.09 px line measured 127.30 px - 13 px too wide - and the seven-band
// card that drew correctly was reported as over its own edge.  A measurement that invents the
// separator is worse than no measurement: it fails the correct layout and passes a wrong one.
struct Glyph { unsigned int cp; float em; };

inline const Glyph* table (std::size_t& count) noexcept
{
    static const Glyph kGlyphs[] = {
{body}
    };
    count = sizeof (kGlyphs) / sizeof (kGlyphs[0]);
    return kGlyphs;
}

// One UTF-8 code point at `p`, and the number of bytes it took.  A malformed sequence is
// returned as a single 0xFFFD swallowed byte by byte, so a bad literal can never silently
// measure as *less* than it draws.
inline unsigned int decode (const char* p, std::size_t& used) noexcept
{
    const auto b = static_cast<unsigned char> (*p);
    if (b < 0x80)                             { used = 1; return b; }
    if ((b & 0xE0) == 0xC0 && p[1] != '\0')   { used = 2; return ((b & 0x1Fu) << 6)
                                                             | (static_cast<unsigned char> (p[1]) & 0x3Fu); }
    if ((b & 0xF0) == 0xE0 && p[1] != '\0' && p[2] != '\0')
                                              { used = 3; return ((b & 0x0Fu) << 12)
                                                             | ((static_cast<unsigned char> (p[1]) & 0x3Fu) << 6)
                                                             |  (static_cast<unsigned char> (p[2]) & 0x3Fu); }
    used = 1; return 0xFFFD;
}

inline float emOf (unsigned int cp) noexcept
{
    std::size_t n = 0;
    const Glyph* g = table (n);
    // the table is sorted by code point, so this stops early on a miss rather than scanning
    for (std::size_t i = 0; i < n; ++i)
    {
        if (g[i].cp == cp) return g[i].em;
        if (g[i].cp > cp) break;
    }
    return 0.55f;                             // an unknown glyph: the table's mean
}

// The advance of a string at `size` px, in px: glyph by glyph, no rounding, no kerning (the
// plugin's text paths do not enable kerning).  Walks **code points**: text is UTF-8 on this
// panel and measuring it byte by byte charged the 2-byte separator twice.
inline float advance (const char* s, float size) noexcept
{
    float total = 0.0f;
    for (const char* p = s; p != nullptr && *p != '\0'; )
    {
        std::size_t used = 1;
        total += emOf (decode (p, used));
        p += used;
    }
    return total * size;
}

inline float advance (const char* s, std::size_t len, float size) noexcept
{
    float total = 0.0f;
    std::size_t k = 0;
    while (k < len)
    {
        std::size_t used = 1;
        total += emOf (decode (s + k, used));
        k += used;
    }
    return total * size;
}

} // namespace aeq::ui::metrics
'''


def main() -> int:
    if not TTF.exists():
        print(f"missing {TTF}", file=sys.stderr)
        return 2
    font = TTFont(TTF)
    upm = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    # ASCII, plus every non-ASCII character that reaches this panel's copy.  Keep this list to
    # what the product draws: the table is a measurement, not a font.
    EXTRA = [
        0x00B7,   # middle dot, the separator in "1.25 kHz  \u00b7  Q 1.40"
        0x2022,   # bullet
        0x2013,   # en dash
        0x2014,   # em dash
        0x00D7,   # multiplication sign
        0x00B0,   # degree
        0x2019,   # right single quote
        0x2026,   # ellipsis
        0x00A0,   # no-break space
    ]
    codes = list(range(32, 127)) + [c for c in EXTRA if c in cmap]
    lines = []
    for code in sorted(set(codes)):
        g = cmap.get(code)
        adv = hmtx[g][0] / upm if g else 0.5
        lines.append(f"        {{0x{code:04X}u, {adv:.4f}f}},")
    OUT.write_text(HEADER.replace("{upm}", str(upm)).replace("{body}", "\n".join(lines)))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(lines)} glyphs, unitsPerEm {upm})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
