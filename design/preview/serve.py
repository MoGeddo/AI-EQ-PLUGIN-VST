#!/usr/bin/env python3
"""serve.py - the design preview, served from the repo root.

Why a script at all: the preview pages reference the plugin's own font with
root-absolute URLs (`/plugin/Source/assets/Cairo-Regular.ttf`), so they are only
correct when the *repository root* is the document root.  Serving
`design/preview/` directly gives you a page with no Arabic in it and nothing says
why, so the rule lives here instead of in someone's shell history.

    python3 design/preview/serve.py                # http://0.0.0.0:8080
    python3 design/preview/serve.py --port 9000

No caching: the panel PNG is regenerated by ui_v6.py, and a preview that serves a
stale render is worse than no preview.
"""
from __future__ import annotations

import argparse
import functools
import http.server
import pathlib
import socketserver

ROOT = pathlib.Path(__file__).resolve().parents[2]


class Handler(http.server.SimpleHTTPRequestHandler):
    extensions_map = {
        **http.server.SimpleHTTPRequestHandler.extensions_map,
        ".ttf": "font/ttf",
        ".woff2": "font/woff2",
        ".webp": "image/webp",
        ".mjs": "text/javascript",
        ".json": "application/json",
        ".csv": "text/plain; charset=utf-8",
    }

    def end_headers(self):
        self.send_header("Cache-Control", "no-store, must-revalidate")
        super().end_headers()

    def log_message(self, fmt, *args):  # one line per request, not a traceback
        print("%s %s" % (self.address_string(), fmt % args), flush=True)


class Server(socketserver.ThreadingTCPServer):
    allow_reuse_address = True
    daemon_threads = True


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=8080)
    ap.add_argument("--host", default="0.0.0.0")
    a = ap.parse_args()

    handler = functools.partial(Handler, directory=str(ROOT))
    with Server((a.host, a.port), handler) as httpd:
        print(f"preview: http://{a.host}:{a.port}/  (root {ROOT})", flush=True)
        print(f"panel:   http://{a.host}:{a.port}/design/preview/ui_v6_1180x700.png", flush=True)
        try:
            httpd.serve_forever()
        except KeyboardInterrupt:
            pass
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
