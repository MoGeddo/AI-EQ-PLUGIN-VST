#!/usr/bin/env python3
"""serve.py - the design preview, served from the repo root.

Why a script at all: the preview pages reference the plugin's own font with
root-absolute URLs (`/plugin/Source/assets/Cairo-Regular.ttf`), so they are only
correct when the *repository root* is the document root.  Serving
`design/preview/` directly gives you a page with no Arabic in it and nothing says
why, so the rule lives here instead of in someone's shell history.

    python3 design/preview/serve.py                # http://0.0.0.0:8080
    python3 design/preview/serve.py --port 9000

No caching: the panel PNG is regenerated by ui_v6.py, and a preview that serves a
stale render is worse than no preview.
"""
from __future__ import annotations

import argparse
import functools
import http.server
import pathlib
import posixpath
import socketserver
from urllib.parse import unquote

ROOT = pathlib.Path(__file__).resolve().parents[2]


# Nothing under these is the preview.  The document root is the repository, which is
# the only way the pages' root-absolute font URLs work - so the server has to know
# what it must NOT hand out: .git (remote URL, credential-helper config), the audio
# corpus, and every other dotfile.
DENY_PREFIXES = (".git", ".github", ".arena", "google_drive", "analysis/out/audio",
                 "_refs", "build", "dist", "plugin/build")
DENY_SUFFIXES = (".wav", ".flac", ".mp3", ".mp4", ".whl", ".pdb")


class Handler(http.server.SimpleHTTPRequestHandler):
    extensions_map = {
        **http.server.SimpleHTTPRequestHandler.extensions_map,
        ".ttf": "font/ttf",
        ".woff2": "font/woff2",
        ".webp": "image/webp",
        ".mjs": "text/javascript",
        ".json": "application/json",
        ".csv": "text/plain; charset=utf-8",
    }

    def end_headers(self):
        self.send_header("Cache-Control", "no-store, must-revalidate")
        self.send_header("X-Content-Type-Options", "nosniff")
        # deliberately no X-Frame-Options / CSP frame-ancestors: the whole point of
        # this server is that the panel is embedded in a preview iframe
        super().end_headers()

    def _denied(self) -> bool:
        rel = posixpath.normpath(unquote(self.path)).lstrip("/")
        rel = rel.split("?")[0]
        if any(seg.startswith(".") and seg not in (".", "..") for seg in rel.split("/")):
            return True
        if any(rel == p or rel.startswith(p + "/") for p in DENY_PREFIXES):
            return True
        return rel.lower().endswith(DENY_SUFFIXES)

    def do_GET(self):
        if self._denied():
            self.send_error(403, "not part of the preview")
            return
        super().do_GET()

    def do_HEAD(self):
        if self._denied():
            self.send_error(403, "not part of the preview")
            return
        super().do_HEAD()

    def log_message(self, fmt, *args):  # one line per request, not a traceback
        print("%s %s" % (self.address_string(), fmt % args), flush=True)


class Server(socketserver.ThreadingTCPServer):
    allow_reuse_address = True
    daemon_threads = True


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=8080)
    ap.add_argument("--host", default="0.0.0.0")
    a = ap.parse_args()

    handler = functools.partial(Handler, directory=str(ROOT))
    with Server((a.host, a.port), handler) as httpd:
        print(f"preview: http://{a.host}:{a.port}/  (root {ROOT})", flush=True)
        print(f"panel:   http://{a.host}:{a.port}/design/preview/ui_v6_1180x700.png", flush=True)
        try:
            httpd.serve_forever()
        except KeyboardInterrupt:
            pass
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
