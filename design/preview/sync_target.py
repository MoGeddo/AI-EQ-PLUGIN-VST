#!/usr/bin/env python3
"""Copy the target curve out of the plugin header into the design preview.

The preview must draw the curve the plugin actually compiles - not a shape an
illustrator liked.  `plugin/Source/model/EnvTargetCurve.h` is generated by
`analysis/scripts/env_target.py` from the 15 mixes, so it is the only authority;
this script reads it and writes `design/preview/target.js`.

    python3 design/preview/sync_target.py

If the header changes and this is not re-run, the preview is stale - which is why
it prints the sha256 of both files.
"""
import hashlib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
HEADER = ROOT / "plugin" / "Source" / "model" / "EnvTargetCurve.h"
OUT = ROOT / "design" / "preview" / "target.js"


def array_named(text, name):
    """The float values of the std::array returned by EnvTargetCurve::<name>()."""
    m = re.search(rf"{name}\(\)\s*\{{.*?std::array<float, kPoints> v \{{(.*?)\}};", text, re.S)
    if not m:
        sys.exit(f"cannot find {name}() in {HEADER}")
    return [float(v) for v in re.findall(r"-?\d+\.\d+", m.group(1))]


def main():
    text = HEADER.read_text(encoding="utf-8")
    level = array_named(text, "level")
    sd = array_named(text, "sd")
    points = int(re.search(r"kPoints\s*=\s*(\d+)", text).group(1))
    fmin = float(re.search(r"kFmin\s*=\s*([\d.]+)", text).group(1))
    per_oct = float(re.search(r"kPointsPerOct\s*=\s*([\d.]+)", text).group(1))
    undefined = float(re.search(r"kUndefined\s*=\s*([\d.]+)", text).group(1))
    if not (len(level) == len(sd) == points):
        sys.exit(f"expected {points} points, got level={len(level)} sd={len(sd)}")

    body = (
        "// Generated by design/preview/sync_target.py - do not edit.\n"
        f"// Source: plugin/Source/model/EnvTargetCurve.h  sha256={hashlib.sha256(text.encode()).hexdigest()[:16]}\n"
        f"window.AEQ_TARGET = {{\n  fmin: {fmin}, pointsPerOct: {per_oct}, undefined: {undefined},\n"
        f"  level: [{', '.join(f'{v:g}' for v in level)}],\n"
        f"  sd:    [{', '.join(f'{v:g}' for v in sd)}]\n}};\n"
    )
    OUT.write_text(body, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(level)} points, {fmin:g} Hz, "
          f"{per_oct:g}/oct)  header sha256={hashlib.sha256(text.encode()).hexdigest()[:16]}")


if __name__ == "__main__":
    main()
