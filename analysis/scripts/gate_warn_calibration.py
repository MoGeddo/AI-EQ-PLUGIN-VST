#!/usr/bin/env python3
"""gate_warn_calibration.py - the warning bars are the measurement, and they still speak.

Three detectors in this plugin are allowed to call a take wrong: rumble, dull and noise.
Three are not - sibilance, 2-4 kHz harshness, 1 kHz nasality - because the 15 dry stems
that define "right" span more of each of those than any fault this script can inject.

Both halves of that sentence are claims, and both are checked here against the numbers the
shipped binary measured (`analysis/out/amir15/warn_stats.json`, regenerated by
`calibrate_warn.py`):

  1. every verdict bar in `plugin/Source/model/WarnThresholds.h` is the midpoint of the
     daylight between his own mixes and a known fault, recomputed here independently
  2. no take of his crosses a bar, and every faulted take does (the strict rule: a bar is
     only a bar if it fires on all of them, not on the average)
  3. the three readouts have no bar at all - a constant that fires on his own records is
     worse than no constant
  4. the de-esser's automatic engagement is recomputed from his own quartiles

    python3 analysis/scripts/gate_warn_calibration.py      # prints WARN CALIBRATION OK
"""
from __future__ import annotations

import json
import os
import re
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CACHE = os.path.join(ROOT, "analysis", "out", "amir15", "warn_stats.json")
HEADER = os.path.join(ROOT, "plugin", "Source", "model", "WarnThresholds.h")
MIN_GAP_DB = 1.0

# detector -> (statistic, which way is bad, its fault key, the header constant)
VERDICTS = {
    "rumble": ("rumble", +1, "rumble", "rumble"),
    "dull": ("airslope", -1, "dull", "airSlope"),
    "noise": ("noisefloor", +1, "noise", "noiseFloor"),
}
READOUTS = {"sib": "sibexc", "harsh": "harshslope", "nasal": "nasalslope"}


def const_of(header: str, name: str) -> float | None:
    m = re.search(rf"static constexpr double {name} = (-?[\d.]+);", header)
    return float(m.group(1)) if m else None


def main() -> int:
    fails: list[str] = []
    if not os.path.exists(CACHE):
        print(f"no stats at {CACHE} - run analysis/scripts/calibrate_warn.py")
        return 2
    data = json.load(open(CACHE, encoding="utf-8"))
    clean, faulted = data["clean"], data["faulted"]
    header = open(HEADER, encoding="utf-8").read()

    # ---- 1 + 2. each verdict bar -----------------------------------------------------
    for det, (key, direction, fkey, const) in VERDICTS.items():
        cs = np.array([e[key] for e in clean.values()])
        fs = np.array([e[key] for e in faulted.get(f"{fkey}_faulted", {}).values()])
        if fs.size == 0:
            fails.append(f"{det}: no faulted takes in the cache")
            continue
        if direction > 0:
            edge_clean, edge_fault = cs.max(), fs.min()
            gap = edge_fault - edge_clean
        else:
            edge_clean, edge_fault = cs.min(), fs.max()
            gap = edge_clean - edge_fault
        bar = (edge_clean + edge_fault) / 2.0
        said = const_of(header, const)
        print(f"  {det:<7} his worst {edge_clean:+7.2f}  fault {edge_fault:+7.2f}  "
              f"gap {gap:+6.2f}  bar {bar:+7.2f}  header {said}")
        if gap < MIN_GAP_DB:
            fails.append(f"{det}: his range and the fault overlap (gap {gap:+.2f} dB) - "
                         "this detector may not be a verdict")
        if said is None:
            fails.append(f"{det}: {const} is not in WarnThresholds.h")
        elif abs(said - bar) > 0.06:
            fails.append(f"{det}: the header says {said}, the measurement says {bar:.2f} "
                         "- regenerate with calibrate_warn.py --write")
        if direction > 0:
            if cs.max() >= (said if said is not None else bar):
                fails.append(f"{det}: one of his own takes would fire ({cs.max():.2f})")
            if fs.min() <= (said if said is not None else bar):
                fails.append(f"{det}: a faulted take would NOT fire ({fs.min():.2f})")
        else:
            if cs.min() <= (said if said is not None else bar):
                fails.append(f"{det}: one of his own takes would fire ({cs.min():.2f})")
            if fs.max() >= (said if said is not None else bar):
                fails.append(f"{det}: a faulted take would NOT fire ({fs.max():.2f})")

    # ---- 3. the readouts have no bar --------------------------------------------------
    for det, key in READOUTS.items():
        cs = np.array([e[key] for e in clean.values()])
        fs = np.array([e[key] for e in faulted.get(f"{det}_faulted", {}).values()])
        if fs.size == 0:
            fails.append(f"{det}: no faulted takes in the cache")
            continue
        gap = fs.min() - cs.max()
        named = [m for m in ("harsh", "nasal", "sib", "sibilance")
                 if re.search(rf"static constexpr double {m}", header, re.I)]
        print(f"  {det:<7} his range spans {np.ptp(cs):5.1f} dB, gap to a fault {gap:+6.2f}"
              f"  -> readout only")
        if gap >= MIN_GAP_DB:
            fails.append(f"{det}: the fault clears his range by {gap:+.2f} dB, so this "
                         "SHOULD be a verdict now - the question changed")
        if named:
            fails.append(f"{det}: WarnThresholds.h still carries a bar ({named[0]}) for a "
                         "detector whose range overlaps a fault")

    # ---- 4. the de-esser's automatic engagement ---------------------------------------
    exc = np.array([e["sibexc"] for e in clean.values()])
    auto = float(np.percentile(exc, 75)) + 4.0
    said = const_of(header, "deEssAuto")
    fired = int((exc > auto).sum())
    print(f"  de-ess  p75 {np.percentile(exc, 75):+.1f} -> auto {auto:+.1f}  header {said}  "
          f"engages on {fired}/{len(exc)}")
    if said is None or abs(said - round(auto, 1)) > 0.06:
        fails.append(f"deEssAuto: header {said}, measurement {auto:.1f}")
    if fired > 1:
        fails.append(f"the de-esser engages on {fired} of his 15 mixes - too eager")

    if fails:
        for f in fails:
            print("  FAIL " + f)
        return 1
    print("WARN CALIBRATION OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
