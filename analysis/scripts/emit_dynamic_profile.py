#!/usr/bin/env python3
"""emit_dynamic_profile.py - write the corpus's dynamic signature into the plugin.

The measurement in analysis/scripts/structure_moves.py found the one thing that
repeats across the 15 dry stems: not the level (never within 3 dB across songs) and
not the shape of an attack (0.79 similarity against a 0.75 chance floor), but the
*profile of how each band moves with loudness* - how many dB of band per dB of the
voice getting louder.  Fifteen songs agree on that profile with a leave-one-out
correlation of 0.92, against 0.00 for the same profiles with the band axis shuffled.

So the plugin should not hand-type those numbers into a header.  This script reads
the measurement and emits it, and G47 re-runs it and fails if the header disagrees -
which means nobody can tune the DSP by editing a constant and quietly keep a gate
that says the numbers came from the corpus.

    /tmp/venv/bin/python analysis/scripts/emit_dynamic_profile.py          # write
    /tmp/venv/bin/python analysis/scripts/emit_dynamic_profile.py --check   # verify

The table is (Hz, slope) with slope in dB of band level per dB of broadband level:
  < 160 Hz  ~0.15-0.34  the low end does not follow the singer - it is held down
  200 Hz-3 kHz ~1.0-1.4 the mids follow, and slightly more than 1:1
  5-13 kHz  ~0.6-0.7   the air is tamed when the voice pushes
Only the bands below 1.0 can be implemented as cuts; a slope above 1 asks for
expansion, which on a dry vocal raises the noise floor with the harmonic.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "analysis" / "out" / "structure" / "moves.json"
DST = ROOT / "plugin" / "Source" / "dsp" / "DynamicProfile.h"

HEADER = '''// GENERATED by analysis/scripts/emit_dynamic_profile.py - do not edit by hand.
//
// What repeats in Amir's 15 dry stems (49 minutes, 4084 sung notes): the *profile* of
// how much each band moves when the voice gets louder, in dB per dB.  Not the level -
// across songs a band's level varies by 5-19 dB while it moves 20-69 dB within a single
// take, so a static target curve is a fit to nothing.  Not the shape of an attack -
// 0.79 similarity against a 0.75 chance floor.  The slope profile: fifteen songs agree
// with a leave-one-out correlation of {corr:.2f} against {null:.2f} when each song's band
// axis is shuffled on its own (300 draws).
//
// Reading the table: 0.15 below 160 Hz means the low end barely follows the singer -
// that is what "held down" looks like as a number; 1.4 between 500 Hz and 1 kHz means
// the mids follow loudness more than 1:1; 0.65 at 10 kHz means the air is tamed.
#pragma once
#include <cmath>

namespace aeq {{

struct CorpusSlope {{ double hz; double slope; }};

// {n} bands, 1/3 octave, from the corpus study.  Interpolated in log frequency.
inline constexpr CorpusSlope kCorpusSlope[] = {{
{rows}
}};
inline constexpr int kCorpusSlopeCount = {n};

// The corpus slope at any frequency, log-interpolated, clamped to the measured range.
inline double corpusSlope(double hz) {{
    if (hz <= kCorpusSlope[0].hz) return kCorpusSlope[0].slope;
    const int n = kCorpusSlopeCount;
    if (hz >= kCorpusSlope[n - 1].hz) return kCorpusSlope[n - 1].slope;
    for (int i = 1; i < n; ++i) {{
        if (hz <= kCorpusSlope[i].hz) {{
            const double a = kCorpusSlope[i - 1].hz, b = kCorpusSlope[i].hz;
            const double t = std::log(hz / a) / std::log(b / a);
            return kCorpusSlope[i - 1].slope + t * (kCorpusSlope[i].slope - kCorpusSlope[i - 1].slope);
        }}
    }}
    return kCorpusSlope[n - 1].slope;
}}

// How many dB a band at `hz` should move, relative to everything else, when the voice
// gets `dLoudDb` louder than the take it was measured on.  Negative = cut.
//
// A band whose corpus slope is below 1 has to be *pulled back* as the voice pushes;
// that is a cut, and it is safe.  A band whose slope is above 1 would have to be
// boosted as the voice pushes, which on a dry vocal lifts the noise floor along with
// the harmonic - so this returns 0 there and the automatic path never expands.
inline double corpusCorrectionDb(double hz, double dLoudDb) {{
    const double s = corpusSlope(hz) - 1.0;
    if (s >= 0.0) return 0.0;
    return s * dLoudDb;
}}

}} // namespace aeq
'''


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    if not SRC.exists():
        print(f"missing {SRC} - run analysis/scripts/structure_moves.py first", file=sys.stderr)
        return 2
    d = json.loads(SRC.read_text(encoding="utf-8"))
    sig = d["signature"]
    rows = "\n".join(f"    {{{s['hz']:.0f}, {s['slopeDb']:.3f}}}," for s in sig)
    text = HEADER.format(corr=d["slopeCorr"], null=d["nullCorr"], rows=rows, n=len(sig))

    if args.check:
        have = DST.read_text(encoding="utf-8") if DST.exists() else ""
        if have != text:
            print("DynamicProfile.h does not match the corpus measurement", file=sys.stderr)
            return 1
        print(f"DynamicProfile.h matches the corpus ({len(sig)} bands, "
              f"slope correlation {d['slopeCorr']:.2f})")
        return 0

    DST.write_text(text, encoding="utf-8")
    print(f"wrote {DST} ({len(sig)} bands)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
