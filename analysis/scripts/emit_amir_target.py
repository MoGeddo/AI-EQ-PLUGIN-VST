#!/usr/bin/env python3
"""emit_amir_target.py - Amir Mahrous's own curve, as a table the DSP can solve against.

Where the numbers come from
---------------------------
`analysis/out/amir15/amir15.json` is the consensus of his **15 dry stems**: a 1/3-octave
band-level spectrum per stem, averaged across the 15, with a leave-one-out spread of
1.05 dB.  That file is generated by the analysis pipeline and is checked in; this script
only *transcribes* it into C++ so nobody types 27 dB values by hand.

Why this is not the corpus table
--------------------------------
`model/TargetCurve.h` is the consensus of 13 songs by 11 engineers - a family average, and
the validation against Amir's stems was not significant (p = 0.0876, docs/06).  This table
is the thing the user actually asked for: *his* curve.  Restore keeps using the family
average (a restore pass must not chase one engineer's taste); Match uses this one when no
reference profile is loaded.

The honest limitation, stated in the header it writes
-----------------------------------------------------
These numbers were measured by the analysis pipeline, not by the plugin's analyser: 1/3
octave, mix of gates, its own window.  The plugin measures 1/12 octave on gated frames.
Comparing the two is the same class of error the profile work fixed (GATES G72), so this
table is a *starting target*, not a certificate: once the stems are on the same machine as
the plugin, `aeq_cli profile` measures them with the plugin's own instrument and that file
should replace this one.

    .venv/bin/python analysis/scripts/emit_amir_target.py --check    # is the header in sync?
    .venv/bin/python analysis/scripts/emit_amir_target.py --write
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "analysis" / "out" / "amir15" / "amir15.json"
HEADER = ROOT / "plugin" / "Source" / "model" / "AmirTarget.h"


def build() -> str:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    cons = data["amir_consensus"]
    hz = [float(v) for v in cons["bands_hz"]]
    db = [float(v) for v in cons["mean_db"]]
    sd = [float(v) for v in cons["sd_db"]]
    loo = float(cons["loo_max_shift_db"])
    n = len(hz)
    assert len(db) == n == len(sd)

    def rows(values, per_line=6, fmt="{:.2f}f"):
        out = []
        for i in range(0, len(values), per_line):
            chunk = ", ".join(fmt.format(v) for v in values[i:i + per_line])
            out.append("        " + chunk + ",")
        return "\n".join(out)

    return f"""// Generated from analysis/out/amir15/amir15.json - do not edit by hand.
// Amir Mahrous's 15 dry stems: 1/3-octave band level, averaged over the stems, in dB.
// Leave-one-out shift across the 15: {loo:.2f} dB (the noise floor of his own material).
// Absolute levels in dBFS; TargetCurve-style interpolation in log2(f), flat outside.
//
// MEASURED BY THE ANALYSIS PIPELINE, NOT BY THIS PLUGIN'S ANALYSER (1/3 octave, its own
// gating, its own window, against the plugin's 1/12 octave on gated frames).  It is a
// starting target, not a certificate: when the stems are on the machine that runs the
// plugin, `aeq_cli profile --from-dir` measures them with the plugin's own instrument and
// that profile replaces this table.
#pragma once
#include <algorithm>
#include <array>
#include <cmath>

namespace aeq {{

struct AmirTarget {{
    static constexpr int kPoints = {n};

    static const std::array<float, kPoints>& hz() {{
        static const std::array<float, kPoints> v {{
{rows(hz, 6, "{:.0f}.0f")}
        }};
        return v;
    }}
    static const std::array<float, kPoints>& db() {{
        static const std::array<float, kPoints> v {{
{rows(db)}
        }};
        return v;
    }}
    // the spread of his own 15 stems, band by band: the dead zone of a match is the
    // natural variation of the material, and this is that variation, not a guess
    static const std::array<float, kPoints>& sd() {{
        static const std::array<float, kPoints> v {{
{rows(sd)}
        }};
        return v;
    }}

    static double at(double f) {{
        const auto& x = hz();
        const auto& y = db();
        if (f <= x.front()) return y.front();
        if (f >= x.back())  return y.back();
        for (int i = 1; i < kPoints; ++i)
            if (x[i] >= f) {{
                const double t = std::log2(f / x[i - 1]) / std::log2(x[i] / x[i - 1]);
                return y[i - 1] * (1.0 - t) + y[i] * t;
            }}
        return y.back();
    }}

    // Same shape, divided by its own 1 kHz - the frame the solver compares in.
    static double shapeAt(double f) {{ return at(f) - at(1000.0); }}

    static double spreadAt(double f) {{
        const auto& x = hz();
        const auto& s = sd();
        if (f <= x.front()) return s.front();
        if (f >= x.back())  return s.back();
        for (int i = 1; i < kPoints; ++i)
            if (x[i] >= f) {{
                const double t = std::log2(f / x[i - 1]) / std::log2(x[i] / x[i - 1]);
                return s[i - 1] * (1.0 - t) + s[i] * t;
            }}
        return s.back();
    }}
}};

}} // namespace aeq
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    want = build()
    have = HEADER.read_text(encoding="utf-8") if HEADER.exists() else ""

    if args.write:
        HEADER.parent.mkdir(parents=True, exist_ok=True)
        HEADER.write_text(want, encoding="utf-8")
        print(f"wrote {HEADER.relative_to(ROOT)} ({len(want)} bytes)")
        return 0

    if have != want:
        print("AmirTarget.h does not match analysis/out/amir15/amir15.json")
        print("  the table was hand-edited, or the analysis changed and the DSP did not")
        print("  run: .venv/bin/python analysis/scripts/emit_amir_target.py --write")
        return 1

    data = json.loads(SOURCE.read_text(encoding="utf-8"))["amir_consensus"]
    print(f"amir target in sync: {len(data['bands_hz'])} bands, "
          f"LOO {data['loo_max_shift_db']:.2f} dB, "
          f"1 kHz re 250 Hz {data['mean_db'][9] - data['mean_db'][14]:+.2f} dB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
