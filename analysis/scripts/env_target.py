#!/usr/bin/env python3
"""
env_target.py - build the reference curve and its spread in the envelope domain,
**from the shipped binary**.

Why it reads the CLI instead of doing the DSP itself:

the plugin compares a measured envelope level with a target and divides the
difference by the spread of the engineer's own mixes.  If the target comes from
one implementation and the measurement from another, the difference between the
two implementations is charged to the song.  That is not a theory - it happened:
with a Python-built target, one of the 15 reference mixes read 4.6 sigma off its
own average, which is arithmetically impossible for a member of the same sample
(at most sqrt(14) ~ 3.7 sigma).  The Python and the C++ analyser do not measure
identical audio (whole take vs first 90 s, different VAD and window), so the two
domains disagree by a couple of dB in the low mids - exactly the band where the
decisions live.

So: run `aeq_cli analyze` on the 15 takes, average its ENVLINE output, and write
the table.  The Python envelope code is still here, as a *cross-check* of the
algorithm (`--verify`), never as the source of the numbers.

Output:
  analysis/out/amir15/env_target.json   per-song curves + the derived table
  analysis/out/amir15/env_target.csv    the curve, human-readable
  plugin/Source/model/EnvTargetCurve.h  the table the plugin compiles in

Usage:  .venv/bin/python analysis/scripts/env_target.py [--wav dir] [--cli path]
        .venv/bin/python analysis/scripts/env_target.py --verify     (algorithm check)
"""
import argparse
import glob
import json
import os
import subprocess

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "analysis", "out", "amir15")
UNDEFINED = 999.0
MIN_SONGS = 8          # at least half the corpus must measure a band to define it


def run_cli(cli, path):
    r = subprocess.run([cli, "analyze", path], capture_output=True, text=True)
    curve = {}
    f0 = 0.0
    for line in r.stdout.splitlines():
        if line.startswith("ENVLINE "):
            _, f, v = line.split()
            curve[float(f)] = float(v)
        elif line.startswith("median F0"):
            f0 = float(line.split(":")[1].split()[0])
    return curve, f0


def build(cli, files):
    curves, f0s = [], []
    for f in files:
        c, f0 = run_cli(cli, f)
        curves.append(c)
        f0s.append(f0)
        print(f"  {os.path.basename(f)[:30]:<32} {len(c)} bands, F0 {f0:.0f}")
    freqs = sorted(set().union(*[set(c) for c in curves]))
    m = np.full((len(curves), len(freqs)), np.nan)
    for i, c in enumerate(curves):
        for j, f in enumerate(freqs):
            if f in c:
                m[i, j] = c[f]
    n = (~np.isnan(m)).sum(axis=0)
    with np.errstate(invalid="ignore"):
        mean = np.nanmean(m, axis=0)
        sd = np.nanstd(m, axis=0, ddof=1)
    defined = n >= MIN_SONGS
    # max |deviation| a member of the sample can show, as a sanity check
    dev = np.abs(m - mean)
    chi = np.nanmax(dev / np.where(sd > 0, sd, np.nan))
    print(f"\ndefined bands: {int(defined.sum())}/{len(freqs)} "
          f"(from {freqs[int(np.argmax(defined))]:.0f} Hz up)")
    print(f"largest member deviation: {chi:.2f} sigma "
          f"(a member of 15 cannot exceed {np.sqrt(len(curves) - 1):.2f})")
    if chi > np.sqrt(len(curves) - 1) + 0.05:
        raise SystemExit("target and measurement are not the same statistic - stop")
    return np.array(freqs), mean, sd, n, defined, f0s, m


def build_header(freqs, mean, sd, defined):
    """The header as text.  This function used to open the shipped file for writing and
    then return its *path* - so every gate run regenerated the curve it was checking, and
    a "dry" comparison against `header` was comparing a path with a string."""
    import io
    header = os.path.join(ROOT, "plugin", "Source", "model", "EnvTargetCurve.h")
    text = io.StringIO()
    if True:
        fh = text
        fh.write("// Generated by analysis/scripts/env_target.py - do not edit by hand.\n"
                 "//\n"
                 "// The same 15 mixes, measured on the harmonic envelope (the vocal-tract curve\n"
                 "// with the harmonic ladder removed), averaged over the mixes, with the\n"
                 "// between-mix spread next to it.  Both come from aeq_cli's own ENVLINE output:\n"
                 "// a target built by the Python reference instead put one of the 15 mixes 4.6\n"
                 "// sigma off its own average, which cannot happen for a member of the sample\n"
                 "// (max sqrt(14) ~ 3.7) - the two implementations were measuring slightly\n"
                 "// different audio, and the difference was being charged to the song.\n"
                 "//\n"
                 "// Levels are re the 900-1150 Hz reference, the same convention as TargetCurve,\n"
                 "// but the two are NOT interchangeable: an envelope level sits ~14 dB below the\n"
                 "// raw level at 200 Hz and ~0.5 dB below at 1.5 kHz.\n"
                 "//\n"
                 "// Bands defined by fewer than 8 of the 15 takes carry kUndefined: this corpus\n"
                 "// sings between 197 and 350 Hz median, and a monophonic voice has no energy\n"
                 "// below its fundamental, so there is nothing to measure down there.\n"
                 "#pragma once\n#include <array>\n#include <cmath>\n#include <algorithm>\n\n"
                 "namespace aeq {\n\nstruct EnvTargetCurve {\n"
                 "    static constexpr int    kPoints      = 86;\n"
                 "    static constexpr double kFmin        = 100.0;\n"
                 "    static constexpr double kPointsPerOct = 12.0;\n"
                 "    static constexpr float  kUndefined   = 999.0f;\n\n")
        # resample onto the 100 Hz, 12/oct grid the header promises
        grid = 100.0 * 2.0 ** (np.arange(86) / 12.0)
        for name, arr in (("level", mean), ("sd", sd)):
            vals_grid = np.interp(np.log2(grid / freqs[0]), np.log2(freqs / freqs[0]), arr)
            is_def = np.interp(grid, freqs, defined.astype(float)) > 0.999
            vals = np.where(is_def, np.round(vals_grid, 3), UNDEFINED)
            fh.write(f"    static const std::array<float, kPoints>& {name}() {{\n"
                     f"        static const std::array<float, kPoints> v {{\n")
            cells = [f"{v:9.3f}f" for v in vals]
            for i in range(0, 86, 6):
                fh.write("     " + ", ".join(cells[i:i + 6]) + ",\n")
            fh.write("        };\n        return v;\n    }\n\n")
        fh.write("""    static bool definedAt(double f) {
        const int i = indexOf(f);
        return i >= 0 && level()[i] < kUndefined * 0.5f;
    }
    static int indexOf(double f) {
        const double x = std::log2(std::max(f, 1.0) / kFmin) * kPointsPerOct;
        const int i = static_cast<int>(std::lround(x));
        return (i >= 0 && i < kPoints) ? i : -1;
    }
    // linear in log2(f), same interpolation as TargetCurve::at; kUndefined outside
    // the measured range, so callers must check definedAt() first.
    static double at(double f) { return interp(level(), f); }
    static double sdAt(double f) { return interp(sd(), f); }
private:
    template <typename T>
    static double interp(const T& v, double f) {
        const double x = std::log2(std::max(f, 1.0) / kFmin) * kPointsPerOct;
        if (x <= 0.0) return v.front();
        if (x >= kPoints - 1) return v.back();
        const int i = static_cast<int>(x);
        const double t = x - i;
        return v[i] * (1.0 - t) + v[i + 1] * t;
    }
};

} // namespace aeq
""")
    return text.getvalue()


def write_header(freqs, mean, sd, defined):
    path = os.path.join(ROOT, "plugin", "Source", "model", "EnvTargetCurve.h")
    text = build_header(freqs, mean, sd, defined)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    return path


def verify(cli, files):
    """cross-check the C++ envelope against the Python reference on one take"""
    import soundfile as sf

    KFFT, KHOP, LIFTER_S, NOTCH_W = 8192, 2048, 0.0035, 0.00018
    path = files[0]
    x, sr = sf.read(path, dtype="float32", always_2d=True)
    x = x.mean(axis=1)[: int(90 * sr)]
    q = np.arange(KFFT) / sr
    freqs = np.fft.rfftfreq(KFFT, 1.0 / sr)
    win = np.hanning(KFFT)
    acc = []
    for i in range(0, len(x) - KFFT, KHOP):
        seg = x[i:i + KFFT]
        if np.sqrt(np.mean(seg ** 2)) < 10 ** (-45 / 20):
            continue
        p = np.log(np.abs(np.fft.rfft(seg * win)) ** 2 + 1e-20)
        c = np.fft.irfft(p, n=KFFT)
        m = (q > 1.0 / 600.0) & (q < 1.0 / 70.0)
        f0 = 1.0 / q[m][np.argmax(c[m])]
        c2 = c.copy()
        for k in (1, 2, 3, 4):
            c2 -= (np.exp(-0.5 * ((q - k / f0) / NOTCH_W) ** 2)
                   + np.exp(-0.5 * ((q + k / f0) / NOTCH_W) ** 2)) * c
        c2[q > LIFTER_S] = 0.0
        acc.append(np.fft.rfft(c2, n=KFFT).real)
    env = np.mean(acc, axis=0)
    curve, _ = run_cli(cli, path)
    ref_py = None
    print(f"\ncross-check on {os.path.basename(path)[:34]}:")
    print(f"  {'Hz':>7} {'python':>9} {'cli':>9} {'diff':>7}")
    rows = []
    for f in sorted(curve):
        sel = (freqs >= f) & (freqs < f * 2 ** (1 / 12))
        if sel.sum() < 2:
            continue
        v = 4.342944819 * float(np.mean(env[sel]))
        if ref_py is None:
            ref_py = v
        rows.append((f, v, curve[f]))
    # both re their own 900-1150 reference
    def norm(vals):
        r = [v for f, v, _ in rows if 900 <= f < 1150]
        return np.mean(r) if r else 0.0
    pref = norm([(f, v, 0) for f, v, _ in rows])
    for f, v, c in rows[::4]:
        print(f"  {f:7.0f} {v - pref:+9.2f} {c:+9.2f} {(v - pref) - c:+7.2f}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--wav", default="/tmp/wav15")
    ap.add_argument("--cli", default=os.path.join(ROOT, "build", "aeq_cli"))
    ap.add_argument("--verify", action="store_true")
    ap.add_argument("--write", action="store_true",
                    help="write the generated header.  Without this the script only "
                         "measures and prints: a gate that runs it must not be able to "
                         "change the curve it is checking (G14 did exactly that, and the "
                         "shipped header moved during an ordinary ledger run)")
    args = ap.parse_args()
    files = sorted(glob.glob(os.path.join(args.wav, "*.wav")))
    if not files:
        raise SystemExit(f"no wav files in {args.wav}")
    if not os.path.exists(args.cli):
        raise SystemExit(f"build the CLI first: g++ -std=c++17 -O2 -Iplugin/Source "
                         f"plugin/cli/main.cpp -o {args.cli}")
    if args.verify:
        verify(args.cli, files)
        return

    print(f"{len(files)} takes through {os.path.basename(args.cli)}")
    freqs, mean, sd, n, defined, f0s, raw = build(args.cli, files)
    header = build_header(freqs, mean, sd, defined)
    print(f"median F0 range: {min(f0s):.0f}-{max(f0s):.0f} Hz")

    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "env_target.json"), "w", encoding="utf-8") as fh:
        json.dump({"freqs": np.round(freqs, 2).tolist(),
                   "target_env_db": [None if not d else round(float(v), 3)
                                     for v, d in zip(mean, defined)],
                   "sd_env_db": [None if not d else round(float(v), 3)
                                 for v, d in zip(sd, defined)],
                   "n_songs": n.tolist(),
                   "f0": f0s,
                   "source": "aeq_cli ENVLINE (the shipped binary)"}, fh, indent=1)
    with open(os.path.join(OUT, "env_target.csv"), "w", encoding="utf-8") as fh:
        fh.write("freq_hz,target_env_db,sd_env_db,n_songs\n")
        for i, f in enumerate(freqs):
            if defined[i]:
                fh.write(f"{f:.1f},{mean[i]:.3f},{sd[i]:.3f},{int(n[i])}\n")
    if not args.write:
        cur = os.path.join(ROOT, "plugin", "Source", "model", "EnvTargetCurve.h")
        old = open(cur, encoding="utf-8").read() if os.path.exists(cur) else ""
        # the header is a pure function of the measurement, so "unchanged" is a text
        # comparison, not a tolerance
        if old == header:
            print("header unchanged (dry run) - the shipped curve is this measurement")
        else:
            import difflib
            moved = sum(1 for l in difflib.unified_diff(old.splitlines(),
                                                        header.splitlines(), n=0, lineterm="")
                        if l.startswith(("+", "-")) and not l.startswith(("+++", "---")))
            print(f"header DIFFERS (dry run): {moved} lines would change "
                  f"- pass --write to regenerate")
        return
    print(f"wrote {header}")
    print(f"wrote {os.path.join(OUT, 'env_target.csv')}")


if __name__ == "__main__":
    main()
