#pragma once

// ArabicText.h - the one and only way text reaches the screen.
//
// Two problems are solved here, and both of them were visible in the 1.2.0 build:
//
// 1. TOFU.  Graphics::drawText() asks the operating system for a typeface.  On a
//    Windows box with no Arabic UI language installed, or inside a DAW that
//    initialises GDI late, that lookup silently returns a font with no Arabic
//    glyphs and every letter becomes a hollow box.  Shipping the font in the
//    binary removes the lookup: Cairo (SIL OFL 1.1) is compiled into the plugin
//    with juce_add_binary_data and handed to Typeface::createSystemTypefaceFor.
//
// 2. SHAPING.  Arabic is cursive and contextual: a letter has up to four shapes
//    and the string has to be reordered right-to-left.  JUCE 8 does shape and
//    bidi correctly, but only on the TextLayout path - drawText() takes the plain
//    GlyphArrangement route, which drops the joining.  Everything here therefore
//    goes through AttributedString + TextLayout, which is the path that runs
//    SimpleShapedText / HarfBuzz / BidiAlgorithm in JUCE 8.
//
// Rule: no other file in the UI calls g.drawText with Arabic.  Call ui::draw().

#include <juce_graphics/juce_graphics.h>

#include <vector>
#include <juce_gui_basics/juce_gui_basics.h>
#include <BinaryData.h>   // generated by juce_add_binary_data(AEQRestoreFonts ...)

namespace aeq::ui {

enum class Face { Regular, SemiBold };

// juce::String (const char*) treats the bytes as ASCII (juce_String.cpp:
// createFromCharPointer (CharPointer_ASCII (t))).  Any byte above 127 therefore
// becomes one character of its own, so a UTF-8 Arabic literal that says "تخنة"
// arrives as the eight characters U+00D8 U+00AA U+00D8 U+00AE ... and the window
// paints a row of .notdef boxes.  That is what the 1.2.1 build did, and it is why
// the Latin in the same sentence rendered perfectly.
//
// Every string in this UI goes through here.  u8() is the only conversion, and it
// is explicit, so nobody can rely on the implicit one by accident again.
inline juce::String u8 (const char* utf8) { return juce::String::fromUTF8 (utf8); }

// A number that keeps its width.  Every readout on this panel changes while the audio
// plays - the level match, the stabiliser's total, the strengths - and a value going from
// 9.4 to 10.1 used to move the glyph after it by half a digit, which reads as the label
// twitching.  `impeccable` calls this tabular figures and `make-interfaces-feel-better`
// calls it "the number must not reflow"; JUCE has no OpenType feature switch, so the
// padding does the same job: the decimal point and the digits sit on the same columns
// whether the value has one digit or two.
inline juce::String num (double value, int decimals, int width)
{
    const juce::String body = juce::String (value, decimals);
    return body.paddedLeft (' ', juce::jmax (width, body.length()));
}

// The embedded typefaces.  Loaded once, on first use, and cached for the process.
juce::Typeface::Ptr typeface(Face face);

// False when the platform refused to build a typeface from the embedded bytes.
// Windows goes through DirectWrite's custom font collection, which can fail (it
// does on a headless runner).  When it fails the UI must still be readable, so
// font() falls back to a system face and this reports which path was taken.
bool embeddedFontLoaded();

// A font at a given height, in the embedded face.
juce::Font font(float height, Face face);

// The single funnel: UTF-8 in, correctly shaped right-to-left text out.
// `text` is a UTF-8 literal; the string is laid out with bidi + shaping enabled.
void draw(juce::Graphics& g, const char* utf8, juce::Rectangle<float> area,
          juce::Justification just = juce::Justification::centredLeft,
          float fontSize = 14.0f, juce::Colour colour = juce::Colours::white,
          Face face = Face::Regular, float extraLineSpacing = 0.0f);

void draw(juce::Graphics& g, const juce::String& utf8, juce::Rectangle<float> area,
          juce::Justification just = juce::Justification::centredLeft,
          float fontSize = 14.0f, juce::Colour colour = juce::Colours::white,
          Face face = Face::Regular, float extraLineSpacing = 0.0f);

// Same, but laid out at a natural size and never taller than `area` - used for the
// explanatory paragraphs where clipping mid-word looks broken.
void drawParagraph(juce::Graphics& g, const char* utf8, juce::Rectangle<float> area,
                   juce::Justification just = juce::Justification::topLeft,
                   float fontSize = 13.0f, juce::Colour colour = juce::Colours::white,
                   Face face = Face::Regular);

void drawParagraph(juce::Graphics& g, const juce::String& utf8, juce::Rectangle<float> area,
                   juce::Justification just = juce::Justification::topLeft,
                   float fontSize = 13.0f, juce::Colour colour = juce::Colours::white,
                   Face face = Face::Regular);

// Greedy word wrap at a given width, measured with the same font the lines are drawn with.
// A sentence on this panel is a claim in a fixed box, and the box does not grow: wrapping it
// with one measurement and drawing it with another is how the footer's sentence came to run
// through the dial labels (1.2.29).  The render (design/preview/ui_v9.py: ar_wrapped) uses
// the same rule and the same metric so the two drawings break at the same word.
std::vector<juce::String> wrapWords(const juce::String& text, float fontSize, float width,
                                    Face face = Face::Regular);

// Baseline pitch for a stack of wrapped lines: 1.25 x the type size.  Not the font's
// ascent+descent (1.874 x for the embedded Cairo), which is what JUCE's TextLayout reports -
// that is the room a line needs to itself, not the distance between two lines of one
// paragraph.
inline float linePitch (float fontSize) { return fontSize * 1.25f; }

// Width the string needs at that size, for laying out chips and pills.
float measure(const juce::String& utf8, float fontSize, Face face = Face::Regular);
float measure(const char* utf8, float fontSize, Face face = Face::Regular);

} // namespace aeq::ui
